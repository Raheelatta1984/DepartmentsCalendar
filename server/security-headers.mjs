/**
 * Security headers in one place so the same policy is served by:
 *
 *   - the serverless API functions (server/app.mjs)
 *   - the local dev server (server/dev.mjs)
 *   - `vite preview` (vite.config.ts)
 *   - the static Vercel deployment (vercel.json)
 *
 * Review: docs/security/credential-storage-review-2026-10-28.md
 * tests/security-headers.test.mjs fails if vercel.json drifts from this file.
 */

/*
 * The built application contains no inline <script>, no eval-style code and no
 * third-party script origins, so the script directive stays strict.
 *
 *   style-src 'unsafe-inline'  Inline style attributes are generated by the
 *                              theme studio / colour pickers (dynamic colours),
 *                              not authored CSS. They cannot be moved to a
 *                              stylesheet without rewriting the theme engine.
 *   img-src https:             Entity logos are administrator-supplied image
 *                              URLs (Settings → entity logo). Images cannot
 *                              execute script, and no script-src origin is
 *                              opened up by this.
 */
export const CONTENT_SECURITY_POLICY = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob: https:",
  "font-src 'self'",
  "connect-src 'self'",
  "object-src 'none'",
  "base-uri 'none'",
  "frame-ancestors 'none'",
  "form-action 'self'",
].join('; ');

/** API responses are JSON documents: nothing may load and nothing may frame them. */
export const API_CONTENT_SECURITY_POLICY = "default-src 'none'; frame-ancestors 'none'; base-uri 'none'";

/** Same two years Vercel already sends for *.vercel.app, so nothing is downgraded. */
export const STRICT_TRANSPORT_SECURITY = 'max-age=63072000; includeSubDomains';

const PAGES_REFERRER_POLICY = 'strict-origin-when-cross-origin';
// The API has always answered `same-origin`; JSON has no subresources to leak a
// referrer to, so keeping the stricter value changes nothing and weakens nothing.
const API_REFERRER_POLICY = 'same-origin';
const PERMISSIONS_POLICY = 'camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()';

/**
 * Headers for HTML and static assets.
 *
 * @param {object} options
 * @param {boolean} options.https send HSTS and upgrade-insecure-requests. Only
 *   set this when the host actually serves HTTPS: upgrade-insecure-requests on
 *   a plain-HTTP preview would rewrite the asset URLs and blank the page.
 * @param {boolean} options.enforceCsp enforce the policy instead of reporting it.
 *   The Vite dev server injects the React Fast Refresh preamble as an inline
 *   module script, which a strict `script-src 'self'` would block, so local
 *   development reports instead of enforcing. Production enforces.
 * @returns {Record<string, string>}
 */
export function pageSecurityHeaders({ https = false, enforceCsp = true } = {}) {
  return {
    [enforceCsp ? 'Content-Security-Policy' : 'Content-Security-Policy-Report-Only']:
      https ? `${CONTENT_SECURITY_POLICY}; upgrade-insecure-requests` : CONTENT_SECURITY_POLICY,
    'X-Content-Type-Options': 'nosniff',
    'X-Frame-Options': 'DENY',
    'Referrer-Policy': PAGES_REFERRER_POLICY,
    'Permissions-Policy': PERMISSIONS_POLICY,
    'Cross-Origin-Opener-Policy': 'same-origin',
    'Cross-Origin-Resource-Policy': 'same-origin',
    ...(https ? { 'Strict-Transport-Security': STRICT_TRANSPORT_SECURITY } : {}),
  };
}

/**
 * Headers for JSON API responses. No CORS header is ever sent: the browser and
 * the API share an origin, and a cross-origin caller must not be able to read
 * an authenticated response.
 *
 * @param {object} options
 * @param {boolean} options.https send HSTS (only meaningful over HTTPS)
 * @returns {Record<string, string>}
 */
export function apiSecurityHeaders({ https = false } = {}) {
  return {
    'Content-Security-Policy': API_CONTENT_SECURITY_POLICY,
    'X-Content-Type-Options': 'nosniff',
    'X-Frame-Options': 'DENY',
    'Referrer-Policy': API_REFERRER_POLICY,
    'Permissions-Policy': PERMISSIONS_POLICY,
    'Cross-Origin-Opener-Policy': 'same-origin',
    'Cross-Origin-Resource-Policy': 'same-origin',
    ...(https ? { 'Strict-Transport-Security': STRICT_TRANSPORT_SECURITY } : {}),
  };
}

/** Apply a header map to a Node response, unconditionally overwriting. */
export function applyHeaders(response, headers) {
  for (const [name, value] of Object.entries(headers)) response.setHeader(name, value);
  return response;
}
