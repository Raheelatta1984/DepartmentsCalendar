#!/usr/bin/env node
/* ------------------------------------------------------------------ */
/* Release-log tooling                                                */
/*                                                                    */
/* One source of truth: src/data/releases.ts.                         */
/*   npm run changelog         regenerate docs/CHANGELOG.md           */
/*   npm run changelog:check   fail if the file is stale or invalid   */
/*                                                                    */
/* The What’s new tab reads the same module, so the screen, the repo  */
/* changelog and CI can never tell different stories.                 */
/* ------------------------------------------------------------------ */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  LATEST_RELEASE_DATE,
  RELEASES,
  RELEASE_ICONS,
  RELEASE_LABELS,
  RELEASE_LINK_VIEWS,
  RELEASE_TONES,
} from '../src/data/releases.ts';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const TARGET = resolve(ROOT, 'docs/CHANGELOG.md');
const CHECK = process.argv.includes('--check');
const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/;

/** Human names for the screens a release can link to. */
const SCREENS = {
  calendar: 'Department calendar',
  delivery: 'DevOps delivery',
  'effort-reports': 'Effort reports',
  admin: 'Master setup',
  organisation: 'Organisation',
  'theme-studio': 'Theme Studio',
  capitalisation: 'Capitalisation pack',
  timesheet: 'Timesheets',
  leave: 'Leave & PTO',
  standups: 'Daily stand-up',
};

const problems = [];
const fail = (message) => problems.push(message);
const unique = (values) => new Set(values).size === values.length;

function validate(releases) {
  if (!releases.length) fail('the release log is empty');
  if (!unique(releases.map((r) => r.title))) fail('release titles must be unique');
  if (!ISO_DATE.test(LATEST_RELEASE_DATE)) fail('LATEST_RELEASE_DATE must be an ISO date (YYYY-MM-DD)');

  releases.forEach((release, index) => {
    const where = `#${index + 1} “${release.title || '(untitled)'}”`;
    if (!release.title?.trim()) fail(`${where} has no title`);
    if (!ISO_DATE.test(release.date ?? '')) fail(`${where} has no ISO date`);
    if (!release.released?.trim()) fail(`${where} has no display date`);
    if (!RELEASE_LABELS.includes(release.label)) fail(`${where} has an unknown label “${release.label}”`);
    if (!RELEASE_TONES.includes(release.tone)) fail(`${where} has an unknown tone “${release.tone}”`);
    if (!RELEASE_ICONS.includes(release.icon)) fail(`${where} has an unknown icon “${release.icon}”`);
    if (!release.description?.trim()) fail(`${where} has no description`);
    if (!Array.isArray(release.bullets) || !release.bullets.length) fail(`${where} needs at least one bullet`);
    release.bullets?.forEach((bullet, b) => {
      if (!bullet?.trim()) fail(`${where} has an empty bullet (#${b + 1})`);
    });
    if (release.link) {
      if (!RELEASE_LINK_VIEWS.includes(release.link.view)) fail(`${where} links to an unknown view “${release.link.view}”`);
      if (!release.link.label?.trim()) fail(`${where} has a link with no label`);
    }
    if (index > 0) {
      const previous = releases[index - 1];
      if (release.date > previous.date) fail(`${where} is newer than the entry above it — keep the log newest first`);
    }
  });

  /* A logged date should read like its ISO date, e.g. 2026-10-31 → “31 October 2026”. */
  releases.forEach((release) => {
    const parsed = new Date(`${release.date}T00:00:00Z`);
    if (Number.isNaN(parsed.getTime())) return;
    const day = parsed.getUTCDate();
    const month = parsed.toLocaleString('en-AU', { month: 'long', timeZone: 'UTC' });
    const expected = `${day} ${month} ${parsed.getUTCFullYear()}`;
    if (release.released !== expected) fail(`“${release.title}” shows “${release.released}” but its date is ${expected}`);
  });
}

function render(releases) {
  const lines = [
    '<!-- Generated by `npm run changelog` from src/data/releases.ts. Do not edit by hand. -->',
    '# Release notes',
    '',
    'The portal’s **What’s new** tab renders this same log from `src/data/releases.ts`, so the screen and this file can never disagree. Newest first.',
    '',
    `**${releases.length} release${releases.length === 1 ? '' : 's'} · last updated ${releases[0]?.released ?? '—'}**`,
    '',
  ];

  releases.forEach((release) => {
    lines.push('---', '', `## ${release.title}`, '', `**${release.released} · ${release.label}**`, '', release.description, '');
    release.bullets.forEach((bullet) => lines.push(`- ${bullet}`));
    if (release.link) {
      lines.push('', `_Where to look: **${SCREENS[release.link.view] ?? release.link.view}** (\`#/${release.link.view}\`) — ${release.link.label}._`);
    }
    lines.push('');
  });

  return `${lines.join('\n').trimEnd()}\n`;
}

validate(RELEASES);

if (problems.length) {
  console.error('Release log is invalid:');
  problems.forEach((problem) => console.error(`  ✗ ${problem}`));
  process.exit(1);
}

const output = render(RELEASES);

if (CHECK) {
  let current = '';
  try {
    current = readFileSync(TARGET, 'utf8');
  } catch {
    console.error('✗ docs/CHANGELOG.md is missing. Run `npm run changelog`.');
    process.exit(1);
  }
  if (current !== output) {
    console.error('✗ docs/CHANGELOG.md is out of date. Run `npm run changelog` and commit the result.');
    process.exit(1);
  }
  console.log(`✓ Release log valid and docs/CHANGELOG.md is current (${RELEASES.length} releases).`);
} else {
  mkdirSync(dirname(TARGET), { recursive: true });
  writeFileSync(TARGET, output);
  console.log(`✓ Wrote docs/CHANGELOG.md (${RELEASES.length} releases, newest ${RELEASES[0].released}).`);
}
